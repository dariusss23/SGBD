        DBMS_OUTPUT.PUT_LINE('EROARE: ID-ul pilotului nu a fost gasit.');
        
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('EROARE NEASTEPTATA: ' || SQLERRM);
END;


