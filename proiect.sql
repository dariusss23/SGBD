-- Conducerea campionatului de Formula 1 doreste o situatie financiara si administrativa a celor mai noi echipe intrate in competitie. 
-- Sa se realizeze o procedura care identifica cele mai noi 5 echipe infiintate si genereaza un raport cu numele, bugetul si numarul sponsorilor activi (status 'YES') ai acestora. 
-- Pentru o procesare eficienta, datele sunt gestionate folosind trei tipuri de colectii: VARRAY, tabele imbricate si tablouri asociative.


CREATE OR REPLACE PROCEDURE p_analiza_echipe IS
    TYPE varray_echipe IS VARRAY(5) OF VARCHAR(100);
    lista_echipe varray_echipe := varray_echipe();

    TYPE tbl_bugete IS TABLE OF NUMBER;
    bugete tbl_bugete := tbl_bugete();

    TYPE tbl_nr_sponsori IS TABLE OF NUMBER INDEX BY VARCHAR(100);
    nr_sponsori tbl_nr_sponsori;

BEGIN
    SELECT nume BULK COLLECT INTO lista_echipe
    FROM ECHIPA_F1
    ORDER BY an_infiintare DESC
    FETCH FIRST 5 ROWS ONLY;

    bugete.EXTEND(lista_echipe.COUNT);
    FOR i IN 1 .. lista_echipe.COUNT LOOP
        SELECT buget INTO bugete(i)
        FROM ECHIPA_F1
        WHERE nume = lista_echipe(i);
        
    END LOOP;

    FOR i IN 1 .. lista_echipe.COUNT LOOP
        SELECT COUNT(*) INTO nr_sponsori(lista_echipe(i))
        FROM ECHIPA_SPONSOR_F1 ES
        JOIN ECHIPA_F1 E ON E.id_echipa = ES.id_echipa
        WHERE E.nume = lista_echipe(i) AND ES.status_activ = 'YES';
    END LOOP;

    DBMS_OUTPUT.PUT_LINE('--- Primele 5 echipe cele mai noi infiintate ---');
    DBMS_OUTPUT.PUT_LINE('');
    FOR i IN 1 .. lista_echipe.COUNT LOOP
        DBMS_OUTPUT.PUT_LINE('Echipa: ' || lista_echipe(i));
        DBMS_OUTPUT.PUT_LINE(' - Buget: ' || bugete(i));
        DBMS_OUTPUT.PUT_LINE(' - Numar sponsori activi: ' || nr_sponsori(lista_echipe(i)));
        DBMS_OUTPUT.PUT_LINE('---------------------------');
    END LOOP;

END;

BEGIN
    p_analiza_echipe;
END;


