            RETURN NULL;
    
        WHEN TOO_MANY_ROWS THEN
            DBMS_OUTPUT.PUT_LINE('Eroare: Exista mai multe modele diferite care ating aceeasi viteza maxima.');
            RETURN NULL;
    
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Eroare neprevazuta: ' || SQLERRM);
            RETURN NULL;
END;


